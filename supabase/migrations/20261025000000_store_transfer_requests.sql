-- Cross-venue stock requests: Store & Inventory's Day Sheet now breaks each
-- ingredient's requirement down by the venue the function is actually AT
-- (events.venue) and compares it against that venue's own cs_venue_allocations
-- qty (Ambria runs one pooled ops item record per ingredient but a separate
-- physical store per venue) — a venue can be short even when the pooled total
-- across all venues looks fine. This table is the "request a transfer from
-- another venue's store" record a store person creates from that shortfall;
-- nothing moves stock automatically, a human still carries the item and marks
-- the request fulfilled once it has.

create table if not exists public.store_transfer_requests (
  id               bigint      generated by default as identity primary key,
  ingredient_name  text        not null,
  ingredient_hindi text,
  unit             text,
  qty              numeric     not null,
  from_venue_code  text,
  from_venue_name  text,
  to_venue_code    text,
  to_venue_name    text,
  status           text        not null default 'open', -- open | fulfilled | cancelled
  note             text,
  requested_by     text,
  requested_at     timestamptz not null default now(),
  fulfilled_by     text,
  fulfilled_at     timestamptz
);
alter table public.store_transfer_requests disable row level security;

-- Realtime: the Requirements tab's transfer-requests panel subscribes to this.
do $$
begin
  alter publication supabase_realtime add table public.store_transfer_requests;
exception when duplicate_object then null;
end $$;
