-- True many-to-many dish -> catalogue section mapping, replacing the single
-- scalar dishes_master.section_id (one dish, one section) with a join table
-- (one dish, zero/one/many sections). No "primary" column on purpose -- the
-- app picks a deterministic tie-break (earliest-created row per dish) in
-- JS (src/lib/dishSections.js's primarySectionFor) for the handful of
-- things that must still resolve to one section (kitchen/Store department
-- routing, the printed Function Plan's one heading/sort position per dish),
-- while everything catalogue-browsing-facing (Sections tab, "Add section
-- from library", the whole-catalogue search, the client-facing proposal
-- preview) shows a dish under every section it belongs to.
--
-- dishes_master.section_id/sort_in_section are deliberately left in place,
-- unused, as a safety net until every consumer is confirmed migrated off
-- them -- a later cleanup migration drops them once that's done.
create table if not exists public.dish_section_links (
  id         bigint      generated by default as identity primary key,
  dish_name  text        not null,
  section_id uuid        not null,
  sort_order integer     not null default 0,
  created_at timestamptz not null default now(),
  unique (dish_name, section_id)
);
alter table public.dish_section_links disable row level security;
-- The table's real primary key is the surrogate `id`, so a DELETE event's
-- realtime payload would otherwise only carry that id (Postgres' default
-- replica identity) -- not dish_name/section_id, which is exactly what the
-- client-side realtime handler (recipeData.js) needs to know WHICH
-- membership was removed. FULL sends every column on both insert/update/
-- delete, matching how dishes_master/dish_catalogue_sections already behave
-- (their own PKs happen to include the columns every DELETE handler reads).
alter table public.dish_section_links replica identity full;

-- One-time backfill: every dish's existing single section_id becomes its
-- first (and, for now, only) membership row, carrying over its old
-- sort_in_section as this row's sort_order. Safe to re-run (ON CONFLICT
-- DO NOTHING against the unique (dish_name, section_id) pair above).
insert into public.dish_section_links (dish_name, section_id, sort_order)
select dish_name, section_id, coalesce(sort_in_section, 0)
from public.dishes_master
where section_id is not null
on conflict (dish_name, section_id) do nothing;

-- Realtime: DishSectionsEditor.jsx's own channel, and recipeData.js's
-- global dish-meta channel, both already subscribe to this table too.
do $$
begin
  alter publication supabase_realtime add table public.dish_section_links;
exception when duplicate_object then null;
end $$;
